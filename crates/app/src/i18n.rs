//! GUI strings in Vietnamese and English. One `Tr` table per language; `{}` in a string is
//! filled in order by `fill`. The default language is Vietnamese (the app is made for
//! Vietnamese schools); English can be chosen in Settings (saved in the config).
//! Words are for people who do not know what "IP", "bitrate" or "encoder" mean: those
//! only appear under Settings › Advanced and the Details of a running cast.

use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Lang {
    Vi,
    En,
}

impl Lang {
    /// Name of the language in itself (for the Settings list).
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::Vi => "Tiếng Việt",
            Lang::En => "English",
        }
    }

    pub fn tr(self) -> &'static Tr {
        match self {
            Lang::Vi => &VI,
            Lang::En => &EN,
        }
    }
}

/// Replaces each `{}` in `template` with the next argument.
pub fn fill(template: &str, args: &[&dyn std::fmt::Display]) -> String {
    let mut out = String::with_capacity(template.len() + 16);
    let mut args = args.iter();
    let mut rest = template;
    while let Some(i) = rest.find("{}") {
        out.push_str(&rest[..i]);
        if let Some(a) = args.next() {
            out.push_str(&a.to_string());
        }
        rest = &rest[i + 2..];
    }
    out.push_str(rest);
    out
}

