    #[test]
    fn placeholders_match_between_languages() {
        // Every string with placeholders must have the same number of `{}` in both languages.
        let count = |s: &str| s.matches("{}").count();
        let pairs = [
            (VI.waiting_recast, EN.waiting_recast),
            (VI.what_title, EN.what_title),
            (VI.display_n, EN.display_n),
            (VI.casting_to, EN.casting_to),
            (VI.showing, EN.showing),
            (VI.h_retry, EN.h_retry),
            (VI.h_retry_first, EN.h_retry_first),
            (VI.pin_body, EN.pin_body),
            (VI.tray_tip, EN.tray_tip),
            (VI.convert_stats, EN.convert_stats),
            (VI.tv_lost, EN.tv_lost),
            (VI.sound_error, EN.sound_error),
            (VI.rate_line, EN.rate_line),
            (VI.reason_loss, EN.reason_loss),
            (VI.reason_keyframes, EN.reason_keyframes),
            (VI.reason_decoder, EN.reason_decoder),
            (VI.no_hw_encoder, EN.no_hw_encoder),
            (VI.mf_error, EN.mf_error),
            (VI.cc_line, EN.cc_line),
            (VI.cc_latency, EN.cc_latency),
            (VI.inst_intro, EN.inst_intro),
            (VI.upd_title, EN.upd_title),
            (VI.upd_version, EN.upd_version),
            (VI.upd_downloading, EN.upd_downloading),
            (VI.upd_ready_short, EN.upd_ready_short),
            (VI.upd_apply_failed, EN.upd_apply_failed),
        ];
        for (vi, en) in pairs {
            assert_eq!(count(vi), count(en), "{vi} / {en}");
        }
    }
